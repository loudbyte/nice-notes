package com.nicenotes.data.db

import com.nicenotes.data.db.entity.NoteEntity
import com.nicenotes.domain.model.Note

fun NoteEntity.toDomain(): Note = Note(
    id = mLocalId,
    globalId = mGlobalId,
    content = mContent,
    status = mStatus,
    createdAt = mCreateTime,
    updatedAt = mUpdateTime,
    timestamp = mTimestamp,
    finishedAt = mFinishTime,
    isDeleted = mIsDelete,
    isLocal = mIsLocal,
    alarmTime = mAlarmTime,
    previousAlarmTime = mAlarmTimePre,
    nextAlarmTime = mNextAlarmTime,
    repeatRule = mRepeatRulePre,
    forceReminder = mForceReminderPre,
    isReminded = isReminded,
    colorIndex = mColorIndex,
    parentId = mParentId,
    systemVersion = mSysVersion,
    extraForceReminder = mExtraForceReminder,
    extraRepeatRule = mExtraRepeatRule,
    isPinned = isPinned,
    isImportant = isImportant,
    isArchived = isArchived,
    position = position,
)

fun Note.toEntity(): NoteEntity = NoteEntity(
    mLocalId = id,
    mGlobalId = globalId,
    mContent = content,
    mStatus = status,
    mCreateTime = createdAt,
    mUpdateTime = updatedAt,
    mTimestamp = timestamp,
    mFinishTime = finishedAt,
    mIsDelete = isDeleted,
    mIsLocal = isLocal,
    mAlarmTime = alarmTime,
    mAlarmTimePre = previousAlarmTime,
    mNextAlarmTime = nextAlarmTime,
    mRepeatRulePre = repeatRule,
    mForceReminderPre = forceReminder,
    isReminded = isReminded,
    mColorIndex = colorIndex,
    mParentId = parentId,
    mSysVersion = systemVersion,
    mExtraForceReminder = extraForceReminder,
    mExtraRepeatRule = extraRepeatRule,
    isPinned = isPinned,
    isImportant = isImportant,
    isArchived = isArchived,
    position = position,
)
