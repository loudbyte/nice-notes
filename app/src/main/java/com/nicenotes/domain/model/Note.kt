package com.nicenotes.domain.model

data class Note(
    val id: String,
    val globalId: String? = null,
    val content: String,
    val status: String = "NEW",
    val createdAt: Long,
    val updatedAt: Long,
    val timestamp: Long,
    val finishedAt: Long? = null,
    val isDeleted: Boolean = false,
    val isLocal: Boolean = true,
    val alarmTime: Long? = null,
    val previousAlarmTime: Long? = null,
    val nextAlarmTime: Long? = null,
    val repeatRule: String = "",
    val forceReminder: Boolean = false,
    val isReminded: Boolean = false,
    val colorIndex: Int = -1,
    val parentId: String? = null,
    val systemVersion: Int = 1,
    val extraForceReminder: Boolean = false,
    val extraRepeatRule: String = "",
    val isPinned: Boolean = false,
    val isImportant: Boolean = false,
    val isArchived: Boolean = false,
    val position: Long = 0L,
)
